test("research, source files, secrets and traversal cannot enter the archive", () => {
  checkArchive(manifest, entries);
  for (const path of [
    "research/probe.ts",
    ".env",
    "src/index.ts",
    "dist/../../secret",
    "dist/\\secret",
  ]) {
    assert.throws(() => checkArchive(manifest, [...entries, `package/${path}`]));
  }
});

