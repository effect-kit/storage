import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { randomUUID } from "node:crypto";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

import { assert, it } from "@effect/vitest";
import { Effect, Schema } from "effect";

import type { PutRequest } from "../../src/requests.js";
import type { CompatibleProvider } from "../../src/s3-compatible/config.js";
import { makeCompatible } from "../../src/s3-compatible/service.js";
import { S3Signing } from "../../src/s3/signing.js";
import { Storage } from "../../src/storage.js";
import { runStorageConformance } from "../../src/testing.js";
import { cleanup, conformanceFixture, environment } from "./s3-fixture.js";

const mode = Schema.decodeUnknownSync(Schema.Literals(["local-rustfs", "hosted"]))(
  process.env.STORAGE_COMPATIBLE_MODE,
);
const ids = ["r2", "minio", "tigris", "spaces", "b2", "wasabi", "scaleway", "hetzner"] as const;
const selected =
  mode === "local-rustfs"
    ? ids
    : [Schema.decodeUnknownSync(Schema.Literals(ids))(process.env.STORAGE_COMPATIBLE_PROVIDER)];
const parsedCredentials = Schema.decodeUnknownSync(
  Schema.Struct({
    accessKeyId: Schema.NonEmptyString,
    secretAccessKey: Schema.NonEmptyString,
    sessionToken: Schema.optional(Schema.NonEmptyString),
  }),
)({
  accessKeyId: process.env.STORAGE_COMPATIBLE_ACCESS_KEY_ID,
  secretAccessKey: process.env.STORAGE_COMPATIBLE_SECRET_ACCESS_KEY,
  ...(process.env.STORAGE_COMPATIBLE_SESSION_TOKEN
    ? { sessionToken: process.env.STORAGE_COMPATIBLE_SESSION_TOKEN }
    : {}),
});
const credentials = {
  accessKeyId: parsedCredentials.accessKeyId,
  secretAccessKey: parsedCredentials.secretAccessKey,
  ...(parsedCredentials.sessionToken ? { sessionToken: parsedCredentials.sessionToken } : {}),
};

if (!/^effect-storage-acceptance\/[A-Za-z0-9_-]+\/$/u.test(environment.prefix) && mode === "hosted")
  throw new Error(
    "Hosted qualification requires an explicitly authorized effect-storage-acceptance/<run>/ prefix",
  );
if (mode === "hosted" && process.env.STORAGE_COMPATIBLE_ALLOW_HOSTED !== "yes")
  throw new Error(
    "Set STORAGE_COMPATIBLE_ALLOW_HOSTED=yes for the authorized existing test bucket",
  );

function configuration(provider: CompatibleProvider) {
  if (mode === "hosted") {
    const raw: unknown = JSON.parse(process.env.STORAGE_COMPATIBLE_CONFIG ?? "null");
    const fields = Schema.decodeUnknownSync(Schema.Record(Schema.String, Schema.Unknown))(raw);
    // The adapter immediately decodes the complete provider-specific boundary.
    return { ...fields, bucket: environment.bucket, credentials } as Parameters<
      typeof makeCompatible
    >[1];
  }
  const base = {
    bucket: environment.bucket,
    ...(environment.endpoint ? { endpoint: environment.endpoint } : {}),
    region: "us-east-1",
    forcePathStyle: true,
    credentials,
  };
  const { region: _region, ...auto } = base;
  if (provider === "r2") return { ...auto, accountId: "a".repeat(32) };
  if (provider === "tigris") return { ...auto, placement: "multi-region" as const };
  if (provider === "spaces") return { ...base, tier: "standard" as const };
  if (provider === "minio")
    return {
      ...base,
      endpoint: environment.endpoint ?? "invalid",
      edition: "community" as const,
      serverVersion: "protocol-fixture-not-minio",
      versioning: false,
    };
  if (provider === "hetzner") return { ...base, versioning: false };
  return base;
}

for (const provider of selected) {
  const acquire = Effect.fnUntraced(function* () {
    const storage = yield* makeCompatible(provider, configuration(provider));
    const prefix = `${environment.prefix}${randomUUID()}/`;
    // Hosted execution is an explicit version-inventory qualification lane. R2
    // lacks versions; delete only the exact keys generated by each test there.
    const keys = new Set<string>();
    yield* Effect.addFinalizer(() =>
      (mode === "local-rustfs" || storage.capabilities.versionedReads === "history"
        ? cleanup(storage, prefix)
        : Effect.forEach(keys, (key) => storage.delete({ key }), { discard: true })
      ).pipe(Effect.orDie),
    );
    const tracked = {
      ...storage,
      put: <E = never, R = never>(input: PutRequest<E, R>) => {
        keys.add(input.key);
        return storage.put(input);
      },
    };
    return { storage: tracked, prefix };
  });

  it.live(
    `${provider}: portable contract on ${mode} (separate from hosted/provider certification)`,
    () =>
      Effect.gen(function* () {
        const results = yield* runStorageConformance(() => conformanceFixture(acquire));
        assert.isTrue(
          results.every((result) => result.status === "passed" || result.status === "skipped"),
        );
      }),
  );

  it.live(
    `${provider}: native multipart inventory, signed grants and exact pinned readback on ${mode}`,
    () =>
      Effect.scoped(
        Effect.gen(function* () {
          const { storage, prefix } = yield* acquire();
          const key = `${prefix}multipart`;
          const upload = yield* storage.multipart.initiate({ key });
          yield* Effect.addFinalizer(() =>
            storage.multipart.abort(upload).pipe(
              Effect.catchReason("StorageError", "InvalidSession", () => Effect.void),
              Effect.orDie,
            ),
          );
          const part = yield* storage.multipart.uploadPart({
            upload,
            partNumber: 1,
            body: new Uint8Array([1, 2, 3]),
          });
          assert.strictEqual((yield* storage.multipart.listParts({ upload })).parts.length, 1);
          const receipt = yield* storage.multipart.complete({ upload, parts: [part] });
          const ref =
            storage.capabilities.versionedReads === "none"
              ? { storeId: storage.storeId, key }
              : receipt.ref;
          const bytes = yield* Storage.getBytes({ ref, maxBytes: 3 }).pipe(
            Effect.provideService(Storage, storage),
          );
          assert.deepStrictEqual(Array.from(bytes), [1, 2, 3]);
          assert.strictEqual(
            (yield* S3Signing.make(storage).sign({ ref, method: "GET", expiresInSeconds: 60 }))
              .method,
            "GET",
          );
          yield* storage.delete({ ref });
          if (mode === "local-rustfs") {
            const { credentials: _credentials, ...publicConfig } = configuration(provider);
            const example = yield* Effect.sync(() =>
              spawnSync(process.execPath, [resolve("examples/compatible.mjs")], {
                timeout: 30_000,
                encoding: "utf8",
                env: {
                  ...process.env,
                  STORAGE_COMPATIBLE_PROVIDER: provider,
                  STORAGE_COMPATIBLE_CONFIG: JSON.stringify(publicConfig),
                  STORAGE_COMPATIBLE_KEY: `${prefix}example`,
                },
              }),
            );
            assert.strictEqual(example.status, 0, example.stderr);
            assert.strictEqual(
              Schema.decodeUnknownSync(
                Schema.fromJsonString(Schema.Struct({ provider: Schema.String })),
              )(example.stdout.trim()).provider,
              provider,
            );
          }
        }),
      ),
  );
  it.live.skipIf(mode !== "local-rustfs")(
    `${provider}: protected multipart checkpoint resumes in a fresh process`,
    () =>
      Effect.scoped(
        Effect.gen(function* () {
          const { prefix } = yield* acquire();
          const directory = yield* Effect.acquireRelease(
            Effect.promise(() => mkdtemp(join(tmpdir(), "storage-profile-restart-"))),
            (root) => Effect.promise(() => rm(root, { recursive: true, force: true })),
          );
          const { credentials: _credentials, ...publicConfig } = configuration(provider);
          const secret = randomBytes(32).toString("base64");
          for (const boundary of ["part-checkpoint", "none"]) {
            const child = yield* Effect.sync(() =>
              spawnSync(
                process.execPath,
                [
                  resolve("test/provider/session-worker/run.mjs"),
                  directory,
                  `${prefix}restart`,
                  boundary,
                  "upload",
                ],
                {
                  timeout: 30_000,
                  encoding: "utf8",
                  env: {
                    ...process.env,
                    STORAGE_SESSION_TEST_KEY: secret,
                    STORAGE_COMPATIBLE_RESTART_PROVIDER: provider,
                    STORAGE_COMPATIBLE_RESTART_CONFIG: JSON.stringify(publicConfig),
                  },
                },
              ),
            );
            assert.strictEqual(child.status, boundary === "none" ? 0 : 73, child.stderr);
          }
          const report = yield* Effect.promise(() =>
            readFile(join(directory, "result.json"), "utf8"),
          );
          assert.strictEqual(
            Schema.decodeUnknownSync(
              Schema.fromJsonString(Schema.Struct({ state: Schema.String })),
            )(report).state,
            "completed",
          );
          assert.strictEqual(
            yield* Effect.promise(() => readFile(join(directory, "parts.log"), "utf8")),
            "1\n2\n",
          );
        }),
      ),
  );
}
